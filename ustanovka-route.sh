#!/bin/sh
# ustanovka-route.sh — ОДИН исполнитель установки движка маршрутизации.
#
# Вызывающих трое, как у DNS: блок переезда, установщик нового клиента и цель
# route в /api/update. Своей копии этой логики они не заводят — три копии
# разъезжаются молча, мы этот класс встречали трижды за два дня.
#
# КОДЫ ВОЗВРАТА — интерфейс, вызывающие судят по ним:
#   0  установлено, приёмка сошлась (версия, файл списка, status отвечает)
#   1  отказ, откат сделан, причина напечатана
#   2  проверка не выполнена (не узнали; не «хорошо» и не «плохо»)
#
# ЧЕГО ПРИЁМКА НЕ УТВЕРЖДАЕТ: что крючок ndm и периодика поставлены. При
# выключённых маршрутах их и не должно быть, и требовать их здесь значило бы
# краснеть на исправном роутере. Замер перенесён туда, где он возможен, —
# см. chto_dalshe и вход --chto-dalshe.
#
# ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО:
#   * своей строки cron и своей установки крючка ndm. Их ставит САМ движок:
#     hook_install зовётся из cmd_on и cmd_ensure и снимает off (ответ кота 1).
#     Писать их своей рукой значит завести вторую дверь к тому же (правило 51);
#   * разбора арха. Движок — POSIX-скрипт, а не бинарь: `file` говорит
#     «POSIX shell script», имён meridian-route-<арх> в раздаче ноль;
#   * включения маршрутов. `mode` не трогаем — включает ЧЕЛОВЕК. Установка и
#     включение это разные решения, и брать второе на себя нельзя.
#
# Клиента и туннель не трогает: qwdtt-ctl не зовётся ни разу.

BASE="http://138.124.78.252:8080/bin"
SUF=""
RSUM="d6560aca85a487205806d16dbf750cdb572283e21b039ffc36c4b5cf649b0499"
RSZ="183060"
RVER="1.25"
T="/tmp/qwdtt-route-ust"
RBIN="/opt/bin/meridian-route"
RLIST="/opt/etc/qwdtt/meridian-route.list"
BAKDIR="/opt/var/backup/qwdtt"
RBAK="$BAKDIR/meridian-route.prev"

say() { echo "[route] $*"; }

# Загрузчик: способ подбирается ОДИН раз и запоминается; успех = код 0 И
# непустой файл. Ключ -T у BusyBox wget собирается опцией FEATURE_WGET_TIMEOUT,
# и там, где её нет, wget падает по сигналу — за ним стоит вариант без -T.
SPOSOB=""; SPOSOB_VYBRAN=""; SKAZANO_PRO_T=0
odnim_sposobom() {
  rm -f "$3"
  case "$1" in
    curl)          curl -fsSL -m 600 -o "$3" "$2" < /dev/null ;;
    "wget -T")     wget -q -T 600 -O "$3" "$2" < /dev/null ;;   # bb-ok: рядом стоит вариант без -T, исход берётся по коду и файлу
    "wget без -T") wget -q -O "$3" "$2" < /dev/null ;;
    *) return 1 ;;
  esac
  _krc=$?
  if [ "$_krc" = 0 ] && [ -s "$3" ]; then return 0; fi
  rm -f "$3"
  return 1
}
skachat() {
  if [ -n "$SPOSOB_VYBRAN" ]; then
    if odnim_sposobom "$SPOSOB_VYBRAN" "$1" "$2"; then SPOSOB="$SPOSOB_VYBRAN"; return 0; fi
    say "    подобранный способ ($SPOSOB_VYBRAN) не сработал — подбираю заново"
    SPOSOB_VYBRAN=""
  fi
  for _sp in curl "wget -T" "wget без -T"; do
    if [ "$_sp" = curl ] && ! command -v curl >/dev/null 2>&1; then continue; fi
    if odnim_sposobom "$_sp" "$1" "$2"; then SPOSOB_VYBRAN="$_sp"; SPOSOB="$_sp"; return 0; fi
    if [ "$_sp" = "wget -T" ] && [ "$SKAZANO_PRO_T" = 0 ]; then
      SKAZANO_PRO_T=1
      say "    с ключом -T здесь не сработало. На части сборок BusyBox он падает —"   # bb-ok: это ТЕКСТ человеку, а не вызов wget
      say "    если видите «Segmentation fault», это оно, и это не ваша поломка."
      say "    Дальше качаю без -T и больше -T не пробую."
    fi
  done
  SPOSOB="ни один вариант не сработал"
  return 1
}

# ЗАВЕДЕНИЕ ФАЙЛА СПИСКА — ЭТО МОСТ, А НЕ РЕШЕНИЕ.
#
# Движок 1.25 в ветке включения требует, чтобы файл существовал:
#     meridian-route.v113test:848  [ -f "$LIST" ] || { say "нет файла списка: $LIST"; return 1; }
# На чистом роутере его не заводит НИКТО: ни install.sh, ни движок, ни панель.
# А обход, который применяли 04.09 — строка 192.0.2.1 из RFC 5737, — сам кот 1
# в комментарии движка (:892-895) назвал негодным: «Обошли заглушкой 192.0.2.1;
# так жить нельзя». Поэтому мы её НЕ КОПИРУЕМ: она выглядит осмысленно ровно
# настолько, чтобы обмануть следующего читателя.
#
# Здесь создаётся ПУСТОЙ файл: :848 проверяет только существование, а list_count
# на пустом файле честно даёт 0. Этого хватает, чтобы ensure прошёл, и ничего не
# утверждается про содержимое.
#
# МОСТ УБИРАЕТСЯ, когда кот 1 починит саму проверку :848 — включение без адресов
# должно быть законным, когда есть доменные группы. Пока этого нет, строка ниже
# держит на себе весь путь, и её надо читать как временную.
zavesti_spisok() {
  if [ -f "$RLIST" ]; then
    say "  файл списка уже есть: $RLIST ($(wc -l 2>/dev/null < "$RLIST") строк)"
    return 0
  fi
  mkdir -p "$(dirname "$RLIST")" 2>/dev/null
  : > "$RLIST" || { say "  ОТКАЗ: не создать $RLIST"; return 1; }
  say "  завёл ПУСТОЙ файл списка: $RLIST"
  say "  (это мост под проверку :848 движка, а не наполнение списка)"
  return 0
}

# vernut_prezhniy — ЕДИНСТВЕННЫЙ путь возврата. Зовётся из ВСЕХ мест, где мы
# уже подменили движок и дальше не сложилось.
#
# Прежде возврат был написан трижды и по-разному: два места без ensure, одно с
# ним, а четвёртое (не удалось завести файл списка) не возвращало ничего вовсе.
# Разница не стилистическая: упавший ensure мог успеть поставить крючок и
# периодику от 1.25, и возврат бинаря 1.7 без ensure оставил бы крючок одной
# версии с движком другой. Четыре копии одного отката — то же самое, за что мы
# держим один исполнитель на три вызывающих (правило 51).
#
# КОПИЯ ПРОВЕРЯЕТСЯ СОДЕРЖИМЫМ ДО ПОДМЕНЫ. На полном флеше `cp` отчитывается
# кодом 0, а на месте остаётся огрызок — и `mv` положил бы этот огрызок поверх
# работающего движка. Тот же дефект мы уже нашли и починили в блоке панели:
# откат, добивающий то, что ещё работало, хуже отсутствия отката (правило 37).
# Не сошлось — лучше оставить НОВЫЙ невключённый движок, чем положить обрывок.
vernut_prezhniy() {
  if [ ! -f "$RBAK" ]; then
    # ГОВОРИМ ФАКТ, А НЕ ДОГАДКУ. Прежняя строка утверждала «на месте остался
    # новый движок» — но функцию зовут и с пути «не удался сам перенос», где по
    # $RBIN не лежит ничего. Утверждение о состоянии, которого функция не
    # смотрела, — это правило 47: показатель, называющий причину вместо факта.
    say "  бэкапа нет ($RBAK) — возвращать нечего."
    if [ -f "$RBIN" ]; then
      _v=$(sed -n 's/^VERSION="\(.*\)"$/\1/p' "$RBIN" 2>/dev/null | head -1)
      say "  по пути $RBIN лежит файл $(wc -c < "$RBIN") Б, версия ${_v:-не прочитана}. Маршруты НЕ включены."
    else
      say "  по пути $RBIN НЕТ НИЧЕГО — движка на роутере сейчас нет."
    fi
    return 1
  fi
  _bs=$(wc -c < "$RBAK")
  cp -p "$RBAK" "$RBIN.back" 2>/dev/null
  _ns=$(wc -c 2>/dev/null < "$RBIN.back")
  if [ "${_ns:-0}" != "$_bs" ]; then
    say "  ОТКАТ НЕ ДЕЛАЮ: копия переписалась не целиком ($_bs -> ${_ns:-0} Б),"
    say "  скорее всего не хватило места. ДВИЖОК НЕ ТРОГАЮ — на месте новый, НЕ включённый."
    say "  Вернуть прежний руками, освободив место:"
    say "      cp -p $RBAK $RBIN.back && mv -f $RBIN.back $RBIN && chmod +x $RBIN && $RBIN ensure"
    rm -f "$RBIN.back"
    return 1
  fi
  mv -f "$RBIN.back" "$RBIN" || { say "  ОТКАТ НЕ УДАЛСЯ: подмена не прошла"; rm -f "$RBIN.back"; return 1; }
  chmod +x "$RBIN"
  # ensure на возвращённой версии обязателен: крючок и периодику ставит сам
  # движок, и после возврата они должны принадлежать ЕЙ, а не той, что ушла.
  "$RBIN" ensure < /dev/null > /dev/null 2>&1
  _erc=$?
  say "  вернулась версия ${BYLA_VER:-неизвестна}, ensure на ней вернул $_erc"
  return 0
}

# Ключ из status. Пусто — значит НЕ СПРОСИЛИ, а не «ноль»: различать обязательно.
klyuch() { sed -n "s/^$1=//p" "$T/status.out" | head -1; }

# chto_dalshe — ПЕРЕНОС ЗАМЕРА В МОМЕНТ, КОГДА ОН ВОЗМОЖЕН.
#
# Приёмка выше НЕ проверяет, что крючок ndm и периодика поставлены: при
# выключённых маршрутах их и не должно быть. Значит путь установки крючка не
# будет проверен НИ НА ОДНОМ роутере парка — если ничего не сделать. Просьба
# ниже и есть то, что делается: она часть приёмки, а не вежливость.
#
# ОДИН ИСТОЧНИК НА ДВЕ ДВЕРИ. Тот же абзац нужен в конце блока переезда, где он
# идёт последним, что человек читает. Копировать текст в блок нельзя — две копии
# разъедутся молча (правило 51), поэтому блок зовёт этот же файл входом
# --chto-dalshe.
#
# ТРИ ИСХОДА, А НЕ ДВА: status не ответил / маршруты выключены / маршруты уже
# включены. Печатать один текст на все три значило бы утверждать недоказанное
# (правило 47): «маршруты сейчас не включены» — это ЗАМЕР, а не предположение.
#
# ЧЕГО ЗДЕСЬ БОЛЬШЕ НЕТ И ПОЧЕМУ. До 09.09.2026 этот абзац обещал человеку, что
# после включения он увидит hook=yes и cron_line=yes. Обещание было снято как
# неверное: hook_install стоит ЗА воротами may_restore (:2296), а те требуют
# mode=black и подтверждения. На свежей установке hook=no законен — и ровно на
# этом пилот дал ЛОЖНЫЙ КРАСНЫЙ, то есть наш текст заставил человека объявить
# исправный роутер сломанным.
#
# Мой промах здесь не в тексте, а в том, что замер про ворота у меня уже был, а
# подпись под ним я оставил прежней. Пока мы САМИ не измерили, при каких
# условиях крючок встаёт, называть человеку ожидаемые значения нельзя: это
# обещание, а не знание. Просим вывод целиком и читаем его сами.
#
# ПОДТВЕРЖДЕНИЕ. Срок замерен, а не пересказан:
#     meridian-route:223  CONFIRM_DEFAULT="120"
#     main.go:3650        const ROUTE_CONFIRM_SEC = 120
#     main.go:3694        api(... action=on&confirm= + ROUTE_CONFIRM_SEC)
# Число 300 в движке — это WHITE_CONFIRM_DEFAULT (:302), окно белого теста,
# другой механизм. Путать их значит назвать человеку неверный срок.
chto_dalshe() {
  _st=""
  [ -x "$RBIN" ] && _st=$("$RBIN" status < /dev/null 2>/dev/null)
  _m=$(echo "$_st"  | sed -n 's/^mode=//p'           | head -1)
  _h=$(echo "$_st"  | sed -n 's/^hook=//p'           | head -1)
  _c=$(echo "$_st"  | sed -n 's/^cron_line=//p'      | head -1)
  _mp=$(echo "$_st" | sed -n 's/^marked_packets=//p' | head -1)
  echo ""
  echo "=================================================================="
  echo "  ЧТО ДАЛЬШЕ — ДВЕ ПРОСЬБЫ, И ОБЕ НАМ ВАЖНЫ"
  echo ""
  if [ -z "$_st" ]; then
    echo "  1. Сказать, включены маршруты или нет, я не могу: движок по пути"
    echo "     $RBIN на status не ответил. Это «не узнали», а не «плохо»."
    echo "     Когда включите маршруты в панели, пришлите нам вывод ЦЕЛИКОМ:"
  elif [ "$_m" = black ]; then
    echo "  1. Маршруты на этом роутере УЖЕ включены (mode=black)."
    echo "     Пришлите нам ПРЯМО СЕЙЧАС вывод ЦЕЛИКОМ:"
  else
    echo "  1. Маршруты сейчас НЕ включены — так и должно быть после установки."
    echo "     Включите их в панели и пришлите нам вывод ЦЕЛИКОМ:"
  fi
  echo ""
  echo "         /opt/bin/meridian-route status"
  echo ""
  echo "     Сверять там ничего не надо и ждать от него ничего не надо —"
  echo "     прочтём сами. Мы ещё не измерили, при каких условиях встаёт"
  echo "     крючок, и называть вам ожидаемые значения было бы обещанием,"
  echo "     а не знанием. Присылайте как есть, целиком."
  echo ""
  echo "  2. ВКЛЮЧИВ МАРШРУТЫ, СРАЗУ ПОДТВЕРДИТЕ ИХ В ПАНЕЛИ —"
  echo "     кнопкой «Всё работает, оставить». На это есть 120 секунд."
  echo "     Не подтвердите — движок снимет всё сам и вернёт как было."
  echo "     Со стороны это выглядит как «маршруты не заработали»,"
  echo "     хотя они работали и были сняты по нашему же предохранителю."
  echo "=================================================================="
}

# Вход для блока переезда: напечатать только абзац и выйти. Ничего не ставит и
# ничего не трогает — можно звать в любой момент.
case "${1:-}" in
  --chto-dalshe) chto_dalshe; exit 0 ;;
esac

say "=== УСТАНОВКА движка meridian-route $RVER, $(date '+%F %T') ==="
mkdir -p "$T" "$BAKDIR"

# ---------- 1. ЗАГРУЗКА И СВЕРКА ----------
say "--- загрузка ($SUF)"
NEW="$T/meridian-route"
if ! skachat "$BASE/meridian-route$SUF" "$NEW"; then
  say "ОТКАЗ: движок не скачался ($SPOSOB). Ничего не тронуто."
  rm -rf "$T"; exit 1
fi
say "скачано способом: $SPOSOB"
GZ=$(wc -c < "$NEW"); GS=$(sha256sum "$NEW" | cut -d' ' -f1)
say "  размер $GZ (ждали $RSZ), sha $(echo "$GS" | cut -c1-16)"
if [ "$GZ" != "$RSZ" ] || [ "$GS" != "$RSUM" ]; then
  say "ОТКАЗ по сумме или размеру. Ничего боевого не тронуто."
  rm -rf "$T"; exit 1
fi
# Движок — скрипт, значит проверяем шебанг, а не ELF: требование к входу должно
# соответствовать тому, что мы ставим.
if [ "$(head -c 2 "$NEW")" != '#!' ]; then
  say "ОТКАЗ: скачанное не похоже на скрипт (нет шебанга). Ничего не тронуто."
  rm -rf "$T"; exit 1
fi
chmod +x "$NEW"

# ---------- 2. МЕСТО ДО ПЕРЕНОСА ----------
DF_OPT="-Pk"; df $DF_OPT / >/dev/null 2>&1 || DF_OPT="-k"   # bb-ok: возможность пробуется, а не предполагается
NADO_KB=$(( (GZ + 1023) / 1024 ))
if [ -f "$RBIN" ]; then
  _p=$(( ($(wc -c < "$RBIN") + 1023) / 1024 ))
  _u=$(wc -c 2>/dev/null < "$RBAK"); _u=$(( (${_u:-0} + 1023) / 1024 ))
  [ "$_p" -gt "$_u" ] && NADO_KB=$(( NADO_KB + _p - _u ))
fi
SVOB_KB=$(df $DF_OPT /opt 2>/dev/null | awk 'NR==2{print $4}')
case "$SVOB_KB" in ''|*[!0-9]*) SVOB_NEPON="$SVOB_KB"; SVOB_KB="" ;; esac
if [ -z "$SVOB_KB" ]; then
  say "  ВНИМАНИЕ: df ответил непонятным (ключи $DF_OPT, поле [${SVOB_NEPON:-пусто}]) — место НЕ проверено"
else
  say "  место на /opt: свободно $SVOB_KB КБ, нужно $NADO_KB КБ"
  if [ "$SVOB_KB" -lt "$NADO_KB" ]; then
    say "ОТКАЗ: не хватило места на /opt. Свободно $SVOB_KB КБ, нужно $NADO_KB КБ."
    # Напечатанная команда обязана запускаться КАК ЕСТЬ (правило 53), значит
    # путь обязан быть полным: из / или /tmp «sh ustanovka-dns.sh» не запустится.
    # Своего входа --chto-snyat у этого файла нет — список печатает исполнитель DNS.
    #
    # ЧЕСТНО ПРО ЭТОТ ПОИСК: на ПЕРВОМ прогоне он не найдёт ничего, и это не
    # дефект, а порядок. В блоке переезда движок идёт РАНЬШЕ DNS (раздел 1 против
    # раздела 2), то есть в момент, когда эта строка может понадобиться,
    # исполнителя DNS на роутере ещё нет. Найдётся он только там, где DNS уже
    # ставили прежде, — тогда список получится подробный.
    #
    # Поэтому запасной путь здесь не «на всякий случай», а ОСНОВНОЙ, и он назван
    # первым в порядке проверки мыслей: /opt/bin/qwdtt-ctl есть на роутере всегда.
    # Оставлять в поиске путь, которого на этом шаге не бывает, и говорить «один
    # список на две двери» было бы неправдой — двери две, но на этом шаге открыта
    # одна.
    _dns=""
    for _p in "$(dirname "$0")/ustanovka-dns.sh" /tmp/qwdtt-pd/ustanovka-dns.sh \
              /opt/etc/qwdtt/ustanovka-dns.sh; do
      [ -f "$_p" ] && { _dns="$_p"; break; }
    done
    # Путь обязан быть АБСОЛЮТНЫМ: dirname "$0" даёт «.», если исполнитель
    # позвали без пути, и напечатанная команда сработает только из этого же
    # каталога — то есть «как есть» лишь по случайности.
    case "$_dns" in /*) : ;; ?*) _dns="$(pwd)/${_dns#./}" ;; esac
    if [ -n "$_dns" ]; then
      say "Посмотреть, что можно снять:  sh $_dns --chto-snyat"
    else
      say "Посмотреть, что можно снять:  /opt/bin/qwdtt-ctl cleanup --list"
    fi
    rm -rf "$T"; exit 1
  fi
fi

# ---------- 3. БЭКАП, ПРОВЕРЕННЫЙ РАЗМЕРОМ ----------
BYLA_VER=""
if [ -f "$RBIN" ]; then
  BYLA_VER=$(sed -n 's/^VERSION="\(.*\)"$/\1/p' "$RBIN" | head -1)
  ISZ=$(wc -c < "$RBIN")
  cp -p "$RBIN" "$RBAK" || { say "ОТКАЗ: бэкап не сделан. Не ставлю."; rm -rf "$T"; exit 1; }
  BSZ=$(wc -c 2>/dev/null < "$RBAK")
  say "  бэкап: прежний $ISZ Б (версия ${BYLA_VER:-неизвестна}) -> $RBAK ${BSZ:-НЕТ} Б"
  if [ "$ISZ" != "${BSZ:-0}" ]; then
    say "ОТКАЗ: копия не совпала по размеру. Без годного бэкапа не ставлю."
    rm -rf "$T"; exit 1
  fi
else
  say "  движка не было — бэкапить нечего"
fi

# ---------- 4. ПОДМЕНА, ПРОВЕРЕННАЯ ЧТЕНИЕМ ----------
mv -f "$NEW" "$RBIN.incoming" && mv -f "$RBIN.incoming" "$RBIN"
LEG=$(wc -c 2>/dev/null < "$RBIN")
if [ "${LEG:-0}" != "$GZ" ]; then
  say "ОТКАЗ: перенос не удался (было $GZ Б, на месте ${LEG:-0} Б) — скорее всего кончилось место."
  vernut_prezhniy
  rm -f "$RBIN.incoming"; rm -rf "$T"; exit 1
fi
chmod +x "$RBIN"
say "  движок на месте: $LEG Б"

# ---------- 5. ФАЙЛ СПИСКА (МОСТ) ----------
# Возврат нужен и ЗДЕСЬ: движок уже подменён. Прежде эта ветка не возвращала
# ничего, и роутер оставался с новым движком, которого нельзя включить.
if ! zavesti_spisok; then
  say "ОТКАЗ: без файла списка ensure не пройдёт. Возвращаю прежний движок."
  vernut_prezhniy
  rm -rf "$T"; exit 1
fi

# ---------- 6. ENSURE ----------
# ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, А ЧТО НЕТ.
#
# Крючок ndm и периодику ставит САМ движок изнутри ensure — своей рукой мы их не
# пишем (правило 51: вторая дверь к тому же). Но ставит он их, только пройдя
# ворота, а при установке ворота закрыты.
#
# «ensure вернул 0» признаком УСПЕХА НЕ ЯВЛЯЕТСЯ, и прежняя приёмка была здесь
# неправа. Замер по самому движку (meridian-route.v113test): у cmd_ensure ЧЕТЫРЕ
# выхода, и все четыре — ноль:
#     :2296  may_restore || return 0                 ворота: mode не black
#     :2297  have iptables && have ipset && ip || return 0
#     :2300  list_empty && ! dns_has_sets -> return 0
#     :2367  return 0                                сделал всё
# «Не пустили» и «сделал» приходят одним и тем же нулём, различить их по коду
# нельзя — это ровно правило 52: тихий выход с кодом 0 значит «не делал».
#
# Поэтому НОЛЬ здесь не засчитывается ни во что. А НЕ-НОЛЬ засчитывается, и
# признак несимметричен намеренно: раз внутри cmd_ensure нулей четыре из
# четырёх, set -e в движке нет, а диспетчер кончается esac, ненулевой код может
# прийти только от ОБОЛОЧКИ — файл не запустился вовсе (нет прав, не тот шебанг,
# синтаксис). Это уже настоящий отказ, и он с откатом.
say "--- ensure (крючок и периодику движок ставит сам, когда откроются ворота)"
"$RBIN" ensure < /dev/null > "$T/ensure.out" 2>&1
ERC=$?
sed 's/^/    /' "$T/ensure.out"
say "  ensure вернул: $ERC   (ноль здесь НЕ означает «сделал» — см. комментарий в файле)"
if [ "$ERC" != 0 ]; then
  say "ОТКАЗ: движок не запустился вовсе. Внутри ensure все выходы нулевые, значит"
  say "код $ERC пришёл от оболочки, а не от логики движка. Возвращаю прежний движок."
  vernut_prezhniy
  rm -rf "$T"; exit 1
fi

# ---------- 7. ПРИЁМКА ----------
say "--- приёмка"
"$RBIN" status < /dev/null > "$T/status.out" 2>&1
SRC=$?
if [ "$SRC" != 0 ] || [ ! -s "$T/status.out" ]; then
  say "ПРОВЕРКА НЕ ВЫПОЛНЕНА: status не ответил (код $SRC). Это не «хорошо» и не «плохо» —"
  say "мы не узнали. Ничего не откатываю: движок на месте, $LEG Б, и запустился без"
  say "ошибки оболочки."
  rm -rf "$T"; exit 2
fi
V=$(klyuch version); H=$(klyuch hook); C=$(klyuch cron_line); LE=$(klyuch list_entries)
M=$(klyuch mode); CONF=$(klyuch confirmed); IFP=$(klyuch iface_present)
say "  version=$V  list_entries=${LE:-НЕ СПРОСИЛИ}  файл списка: $([ -f "$RLIST" ] && echo есть || echo НЕТ)"
# ВОРОТА ПЕЧАТАЕМ, НО ПО НИМ НЕ СУДИМ. Три разные причины «ensure ничего не
# сделал» дают человеку одну строку, если не показать вход (правило 52).
say "  ворота ensure: mode=${M:-пусто}  confirmed=${CONF:-пусто}  iface_present=${IFP:-не спросили}"
# hook и cron_line — НАБЛЮДЕНИЕ, А НЕ ПРИГОВОР.
# Прежде здесь стояло требование hook=yes и cron_line=yes. Оно было неверным:
# при выключённом режиме ensure выходит на may_restore (:2296) РАНЬШЕ
# hook_install (:2335), потому что mode пуст, — то есть приёмка требовала
# невозможного и покраснела бы на полностью исправном роутере.
say "  hook=$H  cron_line=$C   (при выключённых маршрутах это законно и ожидаемо)"
BED=0
[ "$V" = "$RVER" ] || { say "  !!! версия $V, ждали $RVER"; BED=1; }
[ -f "$RLIST" ]    || { say "  !!! файла списка $RLIST нет"; BED=1; }
# list_entries проверяем НА ЧИСЛО, а не на величину, и слабость названа вслух:
# list_count у движка даёт 0 и БЕЗ файла, значит проверка ловит ровно одно —
# «status отвечает не теми ключами, которые мы читаем».
#
# Рядом прежде стояла приписка «сильная проверка здесь — ensure вернул 0». Она
# СНЯТА как неверная (раздел 6: все выходы cmd_ensure нулевые). Честный итог:
# сильной проверки того, что крючок ставится, на этом шаге НЕТ ВООБЩЕ. Это не
# умолчано — это сказано человеку отдельным абзацем в конце.
case "$LE" in
  ''|*[!0-9]*) say "  !!! list_entries=[$LE] — не число; status отвечает не то, что мы читаем"; BED=1 ;;
esac
if [ "$BED" != 0 ]; then
  say "ОТКАЗ: приёмка не сошлась. Возвращаю прежний движок."
  vernut_prezhniy
  rm -rf "$T"; exit 1
fi

say "ГОТОВО: движок $V установлен, файл списка есть, status отвечает своими ключами."
chto_dalshe
rm -rf "$T"
exit 0
